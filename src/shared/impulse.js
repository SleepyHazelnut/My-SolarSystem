/**
 * 一次冲激 + 指数衰减：`A · e^(−decay·t) · sin(ω·t)`
 *
 * ⚠️ `ω` 与 `decay` 的语义**由调用方定**，两个角色的用法不同，所以这里只提供最朴素的式子：
 *    · 太阳的装饰弹簧用**阻尼频率** ωd 振荡，另用 `ζ·ωn` 做衰减（物理正确的阻尼振子）；
 *    · 地球的叶甩动用同一个 ω 既做衰减又做振荡（调参时就是这么定的）。
 *    强行统一 ω 的语义会改掉两边已经调好的手感，所以不做。
 *
 * ⚠️ 一律 **sin 起手**（t=0 时位移为 0）。起手是 cos 的话第一帧就有位移，会「闪一下」。
 */
export function dampedImpulse(t, amp, decay, omega) {
  return amp * Math.exp(-decay * t) * Math.sin(omega * t);
}
